// 教材圖片不在首次安裝一次下載；由 fetch runtime cache 在實際瀏覽時逐步保存。
const APP_SHELL = CORE_ASSETS;

self.addEventListener('install', event => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then(cache => cache.addAll(APP_SHELL))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(key => key.startsWith('kids-drawing-') && key !== CACHE_NAME).map(key => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // Artwork must not be shadowed by an old matching pathname with a
  // different ?art= revision.  Prefer the current file from GitHub Pages.
  const isArtwork = /\/assets\/guides-(?:outline-clean|color-clean|ink-locked)\/[^/]+\.png$/i.test(url.pathname);
  if (isArtwork) {
    event.respondWith(fetch(request, {cache:'no-store'})
      .then(response => {
        if (response.ok) {
          const copy=response.clone();
          event.waitUntil(caches.open(CACHE_NAME).then(cache=>cache.put(request,copy)).catch(()=>{}));
        }
        return response;
      })
      .catch(async () => (await caches.match(request)) || (await caches.match(request, {ignoreSearch:true})) || Response.error())
    );
    return;
  }
  const isCoreCode = ['index.html','styles.bundle.css','app.js','lineart.js','manifest.webmanifest'].some(name => url.pathname.endsWith('/'+name));
  if (request.mode === 'navigate' || isCoreCode) {
    event.respondWith(
      fetch(request, {cache:'no-store'})
        .then(response => {
          if (response && response.ok) {
            const copy = response.clone();
            caches.open(CACHE_NAME).then(cache => cache.put(request, copy));
          }
          return response;
        })
        .catch(() => caches.match(request, {ignoreSearch:true}).then(cached => cached || caches.match('./index.html', {ignoreSearch:true})))
    );
    return;
  }

  event.respondWith(
    caches.match(request, {ignoreSearch:true}).then(cached => cached || fetch(request).then(response => {
      if (response && response.ok) {
        const copy = response.clone();
        caches.open(CACHE_NAME).then(cache => cache.put(request, copy));
      }
      return response;
    }))
  );
});
